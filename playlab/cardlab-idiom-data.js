const normalizeIdiomQuizText = (value) => String(value || '').trim();

const shuffleIdiomQuizChoices = (items = []) => {
    const next = Array.isArray(items) ? [...items] : [];
    for (let index = next.length - 1; index > 0; index -= 1) {
        const swapIndex = Math.floor(Math.random() * (index + 1));
        [next[index], next[swapIndex]] = [next[swapIndex], next[index]];
    }
    return next;
};

const uniqueIdiomQuizWords = (items = []) => {
    const seen = new Set();
    return (Array.isArray(items) ? items : [])
        .map((item) => normalizeIdiomQuizText(item))
        .filter((item) => {
            if (!item || seen.has(item)) return false;
            seen.add(item);
            return true;
        });
};

const buildIdiomQuizImageUrl = (stageNumber, questionNumber) => (
    `images/2cuts/level-${stageNumber}-${questionNumber}.webp`
);

const buildIdiomStageQuestions = (stageNumber, stageId, rawRows = '') => {
    const parsedRows = String(rawRows || '')
        .split('\n')
        .map((row) => normalizeIdiomQuizText(row))
        .filter((row) => /^\d+\./.test(row))
        .map((row, index) => {
            const normalized = row.replace(/^\d+\.\s*/, '').trim();
            const match = normalized.match(/^(.*?)\s*\((.+)\)$/);
            if (!match) return null;
            const answer = normalizeIdiomQuizText(match[1]);
            const meaning = normalizeIdiomQuizText(match[2]);
            if (!answer || !meaning) return null;
            return {
                id: `${stageId}-q-${String(index + 1).padStart(2, '0')}`,
                word: answer,
                answer,
                title: answer,
                meaning,
                imageUrl: buildIdiomQuizImageUrl(stageNumber, String(index + 1).padStart(2, '0'))
            };
        })
        .filter(Boolean);

    const answerPool = uniqueIdiomQuizWords(parsedRows.map((question) => question.answer));

    return parsedRows.map((question, index) => {
        const distractors = shuffleIdiomQuizChoices(
            answerPool.filter((word) => word !== question.answer)
        ).slice(0, 3);
        return {
            ...question,
            choices: shuffleIdiomQuizChoices([question.answer, ...distractors]).map((value, choiceIndex) => ({
                id: `${stageId}-choice-${index}-${choiceIndex}`,
                value
            }))
        };
    });
};

