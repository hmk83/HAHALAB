const shuffleJosaChoices = (items = []) => {
  const next = Array.isArray(items) ? [...items] : [];
  for (let index = next.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [next[index], next[swapIndex]] = [next[swapIndex], next[index]];
  }
  return next;
};

const normalizeJosaSentence = (value) => String(value || '')
  .replace(/\s+([.,!?])/g, '$1')
  .replace(/\s+/g, ' ')
  .trim();

const splitCompoundAnswer = (value) => String(value || '')
  .split(/\s*-\s*/)
  .map((item) => item.trim())
  .filter(Boolean);

const buildJosaStageQuestions = (stageId, hintText, rawRows = '') => (
  String(rawRows || '')
    .split('\n')
    .map((row) => String(row || '').trim())
    .filter((row) => /\/\s*(?:정답|오답|기답)\s*:/.test(row))
    .map((row, index) => {
      const normalized = row.replace(/^\d+\.\s*/, '').trim();
      const statementMatch = normalized.match(/^(.*?)\s*\/\s*정답:\s*(.*?)\s*(?:\/\s*(?:오답|정답|기답)\s*:\s*(.*))?$/);
      if (!statementMatch) return null;
      const [, statementPart = '', answerPart = '', distractorPartRaw = ''] = statementMatch;
      const statement = String(statementPart || '').trim();
      const answer = String(answerPart || '').trim();
      const distractors = String(distractorPartRaw || '')
        .split(/\s*,\s*/)
        .map((item) => item.trim())
        .filter(Boolean)
        .slice(0, 3);
      if (!statement || !answer || distractors.length < 2) return null;

      const blankCount = (statement.match(/\[\s*\?\s*\]/g) || []).length || 1;
      const answerParts = splitCompoundAnswer(answer);
      let answerIndex = 0;
      const promptText = normalizeJosaSentence(statement.replace(/\[\s*\?\s*\]/g, '____'));
      const sentence = normalizeJosaSentence(statement.replace(/\[\s*\?\s*\]/g, () => {
        if (!answerParts.length) return answer;
        const nextAnswer = answerParts[Math.min(answerIndex, answerParts.length - 1)] || answer;
        answerIndex += 1;
        return nextAnswer;
      }));

      return {
        id: `${stageId}-q-${String(index + 1).padStart(2, '0')}`,
        promptText,
        sentence,
        word: answer,
        answer,
        answerParts,
        blankCount,
        hintText: String(hintText || '').trim(),
        choices: shuffleJosaChoices([answer, ...distractors]).map((value, choiceIndex) => ({
          id: `${stageId}-choice-${index}-${choiceIndex}`,
          value
        }))
      };
    })
    .filter(Boolean)
);

