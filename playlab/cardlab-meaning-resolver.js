  function uniqueWords(items = []) {
    const seen = new Set();
    return (Array.isArray(items) ? items : [])
      .map((item) => normalizeText(item))
      .filter((item) => {
        if (!item || seen.has(item)) return false;
        seen.add(item);
        return true;
      });
  }

