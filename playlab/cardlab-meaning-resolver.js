  function resolveJosaMeaning(word, context = {}) {
    const normalized = normalizeKey(word);
    if (!normalized) return '';
    if (normalized.includes('-')) {
      const parts = normalized.split('-').map((item) => normalizeKey(item)).filter(Boolean);
      if (parts.length > 1) {
        const partMeanings = parts.map((part) => JOSA_MEANINGS[part] || '');
        if (partMeanings.every(Boolean)) {
          return parts.map((part, index) => `${part}: ${partMeanings[index]}`).join(' · ');
        }
        return `${parts.join('·')}처럼 여러 조사를 함께 쓰는 조합이에요.`;
      }
    }
    if (Object.prototype.hasOwnProperty.call(JOSA_MEANINGS, normalized)) {
      return JOSA_MEANINGS[normalized];
    }
    return '';
  }

