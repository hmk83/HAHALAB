  function resolveSynonymContextMeaning(word, context = {}) {
    const normalizedWord = normalizeKey(word);
    if (!normalizedWord) return '';

    const relatedWords = uniqueWords([
      context.promptWord,
      context.answerWord,
      context.selectedWord,
      context.referenceWord
    ]).map((item) => normalizeKey(item));

    for (const entry of SYNONYM_CONTEXT_MEANINGS) {
      if (normalizeKey(entry.word) !== normalizedWord) continue;
      const required = Array.isArray(entry.related) ? entry.related.map((item) => normalizeKey(item)) : [];
      if (!required.length || required.some((item) => relatedWords.includes(item))) {
        return entry.meaning;
      }
    }

    return '';
  }

  function resolveSynonymMeaning(word, context = {}) {
    const normalized = normalizeText(word);
    if (!normalized) return '';

    const contextual = resolveSynonymContextMeaning(normalized, context);
    if (contextual) return contextual;

    const tasteMeaning = resolveTasteMeaning(normalized, context);
    if (tasteMeaning) return tasteMeaning;

    const exact = resolveExactMeaning(normalized, context);
    if (exact) return exact;

    const kind = normalizeText(context.kind || '');
    if (kind.includes('유의')) {
      const referenceWords = uniqueWords([context.answerWord, context.promptWord])
        .filter((item) => normalizeKey(item) !== normalizeKey(normalized));
      for (const referenceWord of referenceWords) {
        const referenceMeaning = resolveExactMeaning(referenceWord, context);
        if (referenceMeaning) return referenceMeaning;
      }
    }

    return '';
  }

