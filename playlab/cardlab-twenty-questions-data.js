  function buildSupplementalHints(spec) {
    const firstHint = GROUP_FIRST_HINTS[spec.group] || '이것은 이름을 맞혀야 하는 낱말이에요.';
    const body = [
      ...(spec.clues || []),
      `'${spec.answer.slice(0, 1)}'로 시작하는 이름이에요.`,
      `${spec.answer.length}글자 이름이에요.`
    ];
    const fillers = GROUP_FILLER_HINTS[spec.group] || [];
    const unique = Array.from(new Set([firstHint, ...body, ...fillers]))
      .filter((hint) => hint && hint !== spec.finalHint);
    let fillerIndex = 0;
    while (unique.length < 19) {
      const filler = SUPPLEMENTAL_GENERIC_FILLERS[fillerIndex % SUPPLEMENTAL_GENERIC_FILLERS.length];
      if (!unique.includes(filler)) unique.push(filler);
      fillerIndex += 1;
    }
    return [...unique.slice(0, 19), spec.finalHint];
  }

  function normalizeTwentyHints(answer, hints, group) {
    const firstHint = GROUP_FIRST_HINTS[group] || GROUP_FIRST_HINTS.animal;
    const cleaned = hints
      .map((hint) => cleanHint(answer, hint))
      .filter(Boolean)
      .filter((hint) => !isCommonFirstHint(hint, firstHint));
    const unique = Array.from(new Set([firstHint, ...cleaned]));
    return unique.slice(0, 20);
  }

  function isCommonFirstHint(hint, firstHint) {
    const firstWithoutPrefix = firstHint.replace(/^이것은\s+/, '');
    return hint === firstHint
      || hint === firstWithoutPrefix
      || hint === '이것은 동물입니다.'
      || Object.values(GROUP_FIRST_HINTS).includes(hint)
      || Object.values(GROUP_FIRST_HINTS).map((value) => value.replace(/^이것은\s+/, '')).includes(hint)
      || /생명체입니다\.$/.test(hint)
      || /동물 분류에 속합니다\.$/.test(hint);
  }

